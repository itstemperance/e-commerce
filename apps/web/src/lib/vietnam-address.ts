export const POPULAR_PROVINCES = Object.keys(VIETNAM_ADDRESS_DATA);

export function getDistricts(province: string): string[] {
  if (!province || !VIETNAM_ADDRESS_DATA[province]) return [];
  return Object.keys(VIETNAM_ADDRESS_DATA[province]);
}

export function getWards(province: string, district: string): string[] {
  if (!province || !district) return [];
  const pData = VIETNAM_ADDRESS_DATA[province];
  if (!pData || !pData[district]) return [];
  return pData[district];
}

export function formatFullAddress(
  street: string,
  ward?: string,
  district?: string,
  province?: string,
): string {
  const parts: string[] = [];
  if (street.trim()) parts.push(street.trim());
  if (ward?.trim()) parts.push(ward.trim());
  if (district?.trim()) parts.push(district.trim());
  if (province?.trim()) parts.push(province.trim());
  return parts.join(', ');
}
